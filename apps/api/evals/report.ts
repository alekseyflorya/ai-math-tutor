import { ERROR_TYPES } from '@tutor/shared';
import {
  checkViolations,
  pct,
  violations,
  type CaseResult,
  type CheckCaseResult,
  type CheckSummary,
  type Summary,
} from './metrics';

export interface RunInfo {
  date: string;
  provider: string;
  model: string;
  concurrency: number;
  durationMs: number;
  filter?: string;
  /** false while a run is unfinished (stopped by the daily quota) */
  complete?: boolean;
}

const SHORT: Record<string, string> = {
  DISTRIBUTION: 'DIST',
  SIGN_TRANSFER: 'SIGN',
  COMBINING_LIKE_TERMS: 'COMB',
  INVERSE_OPERATION: 'INV',
  ONE_SIDE_ONLY: 'ONE',
  ARITHMETIC: 'ARITH',
  OTHER: 'OTHER',
  FAILED: 'failed',
};

const frac = (r: { ok: number; total: number }) => `${pct(r)} (${r.ok}/${r.total})`;
const oneLine = (s: string) => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

/** The headline numbers, one row: also used for the README comparison table. */
export function headlineRow(info: RunInfo, s: Summary): string[] {
  return [
    `\`${info.model}\``,
    frac(s.accuracy),
    pct(s.invalidJson),
    `${s.latency.p50} / ${s.latency.p95} ms`,
    pct(s.rules.level1Question),
    pct(s.rules.noFinalAnswer),
    pct(s.rules.level3CorrectedOnly),
    pct(s.rules.level2OtherNumbers),
    pct(s.rules.language),
    pct(s.rules.latexIntact),
  ];
}

export const HEADLINE_HEADER = [
  'Model',
  'Error type accuracy',
  'Invalid JSON',
  'Latency p50 / p95',
  'L1 is a question',
  'No final answer',
  'L3 = corrected step only',
  'L2 on other numbers',
  'Language matches',
  'LaTeX intact',
];

export const CHECK_HEADER = [
  'Model',
  'Cases',
  'L1 is a question',
  'No value of a side',
  'No computed line',
  'L3 = operations, no results',
  'L2 on other numbers',
  'Language matches',
  'LaTeX intact',
  'Invalid JSON',
  'Latency p50 / p95',
];

export function checkHeadlineRow(info: RunInfo, s: CheckSummary): string[] {
  return [
    `\`${info.model}\``,
    String(s.cases),
    pct(s.level1Question),
    pct(s.noValue),
    pct(s.noComputedLine),
    pct(s.level3OperationsOnly),
    pct(s.level2OtherNumbers),
    pct(s.language),
    pct(s.latexIntact),
    pct(s.invalidJson),
    `${s.latency.p50} / ${s.latency.p95} ms`,
  ];
}

function renderChecks(info: RunInfo, s: CheckSummary, results: readonly CheckCaseResult[]): string {
  const failures = results.flatMap((r) =>
    r.hints.flatMap((h) =>
      checkViolations(h, r.locale).map((v) => [
        r.id,
        `L${h.level}`,
        v,
        h.message ? oneLine(h.message).slice(0, 220) : '—',
      ]),
    ),
  );
  return `
## Check by substitution

A slip while checking the answer (\`evals/check-cases.ts\`: left or right side, in a multiplication or
an addition, EN and UK). Level 1 is \`checkDiagnosePrompt\`, levels 2 and 3 are \`hintPrompt\` with the
check's own ladder, as the API builds them. No level may state the value of a side or the result of
the operation that slipped, or show a computed check line (the engine judges each line it finds);
level 3 lists the operations without their results.

${table(CHECK_HEADER, [checkHeadlineRow(info, s)])}

- Calls that failed even after the retry: ${frac(s.failedCalls)}

### Rule violations

${failures.length ? table(['Case', 'Level', 'Rule', 'Message'], failures) : 'None.'}
`;
}

export function renderReport(
  info: RunInfo,
  s: Summary,
  results: readonly CaseResult[],
  check?: { summary: CheckSummary; results: readonly CheckCaseResult[] },
): string {
  const cols = [...ERROR_TYPES, 'FAILED'] as const;
  const confusion = table(
    ['expected ↓ / predicted →', ...cols.map((c) => SHORT[c]!)],
    ERROR_TYPES.map((t) => [
      SHORT[t]!,
      ...cols.map((c) => {
        const n = s.confusion[t][c];
        return c === t ? `**${n}**` : n ? String(n) : '·';
      }),
    ]),
  );

  const failures = results.flatMap((r) =>
    r.hints.flatMap((h) =>
      violations(h, r.locale).map((v) => [
        r.id,
        `L${h.level}`,
        v,
        h.message ? oneLine(h.message).slice(0, 220) : '—',
      ]),
    ),
  );
  const misses = results
    .filter((r) => r.predicted !== r.expected)
    .map((r) => [
      r.id,
      SHORT[r.expected]!,
      r.predicted ? SHORT[r.predicted]! : 'failed',
      oneLine(r.misconception ?? '—'),
    ]);

  return `# Tutor eval — ${info.model}
${info.complete === false ? '\n> **Incomplete run** (stopped by the daily quota). Finish it with `pnpm eval --resume <this file>.json`.\n' : ''}
${info.date} · provider \`${info.provider}\` · ${s.cases} cases${info.filter ? ` (only ${info.filter})` : ''} · concurrency ${info.concurrency} · ${(info.durationMs / 1000).toFixed(0)} s

Generated by \`pnpm eval\` (apps/api/scripts/eval.ts). Each case: one diagnosis (\`diagnosePrompt\`, which is
also hint level 1), then hint levels 2 and 3 (\`hintPrompt\`) in the remediation context, exactly as the API
builds them. Correctness of every line quoted by the tutor is decided by the math engine.

## Summary

${table(HEADLINE_HEADER, [headlineRow(info, s)])}

- Calls that failed even after the retry: ${frac(s.failedCalls)}
- Latency is per successful model attempt: diagnosis ${s.latency.byPurpose.diagnose.p50} / ${s.latency.byPurpose.diagnose.p95} ms, hints ${s.latency.byPurpose.hint.p50} / ${s.latency.byPurpose.hint.p95} ms (p50 / p95)
- Accuracy by locale: EN ${frac(s.byLocale.en)}, UK ${frac(s.byLocale.uk)}

## Error type accuracy

${table(
  ['Type', 'Accuracy'],
  ERROR_TYPES.map((t) => [t, frac(s.byType[t])]),
)}

### Confusion matrix

${confusion}

### Misdiagnosed cases

${misses.length ? table(['Case', 'Expected', 'Predicted', 'Model’s misconception'], misses) : 'None.'}

## Hint rule violations

${failures.length ? table(['Case', 'Level', 'Rule', 'Message'], failures) : 'None.'}
${check && check.results.length ? renderChecks(info, check.summary, check.results) : ''}`;
}
